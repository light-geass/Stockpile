"""Watchlists persisted in PostgreSQL (Supabase). This is the app's only stock list: `universe.json` was the old
read-only default and is now imported ONCE as "Watchlist 1" by the seed below, then it is gone from the codebase.

Design decisions that shape this module:
  * The connection string comes only from the server environment (`DATABASE_URL` / `SUPABASE_DATABASE_URL`) and is
    treated as a secret — it is redacted from logs and never sent to the browser.
  * The schema is migrated forward-only on first use of every process; the migrations are idempotent, so a redeploy
    re-runs them safely and never touches existing rows.
  * The seed is guarded by an advisory lock + marker rows, so concurrent workers on a fresh database cannot duplicate
    it, and user edits after the first import are never overwritten.
  * There is no in-memory fallback: if the database cannot be reached, callers get `WatchlistError` and say so, rather
    than silently analysing a different (empty/invented) list.

Cap buckets ("Large"/"Mid"/"Small", Scout's shortlist groups) used to live in universe.json. They are preserved per
list item so the one-time import keeps today's behaviour; a stock added from search has no bucket and is its own group.
"""
