# Forward-only. Every statement is safe to re-run on an existing database.
# `id` is a uuid generated by the app: the browser sees that id (`uid` in the API) and the DB `id` is never exposed,
# so a table created by an earlier draft (with an extra `uid`/`position` column) stays fully compatible.
MIGRATIONS = [
    """CREATE TABLE IF NOT EXISTS watchlist_migrations(
         key TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())""",
    """CREATE TABLE IF NOT EXISTS watchlists(
         id UUID PRIMARY KEY,
         name TEXT NOT NULL,
         created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
         updated_at TIMESTAMPTZ NOT NULL DEFAULT now())""",
    """CREATE TABLE IF NOT EXISTS watchlist_items(
         id UUID PRIMARY KEY,
         watchlist_id UUID NOT NULL REFERENCES watchlists(id) ON DELETE CASCADE,
         provider_symbol TEXT NOT NULL,
         symbol TEXT NOT NULL,
         name TEXT NOT NULL,
         position INT NOT NULL DEFAULT 0,
         created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
         UNIQUE(watchlist_id, provider_symbol))""",
    """CREATE INDEX IF NOT EXISTS ix_watchlist_items_list ON watchlist_items(watchlist_id, position)""",
    # A table created by an earlier draft lacks these: add them so this schema works on either layout.
    """ALTER TABLE watchlists ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now()""",
    """ALTER TABLE watchlist_items ADD COLUMN IF NOT EXISTS position INT NOT NULL DEFAULT 0""",
    """CREATE UNIQUE INDEX IF NOT EXISTS ux_watchlist_items_symbol
         ON watchlist_items(watchlist_id, provider_symbol)""",
    # Provenance only (the browser never supplies these); a pre-existing column means it must be nullable.
    """DO $$ BEGIN
         ALTER TABLE watchlist_items ADD COLUMN sector TEXT;
       EXCEPTION WHEN duplicate_column THEN NULL; END $$""",
    """DO $$ BEGIN
         ALTER TABLE watchlist_items ADD COLUMN cap_segment TEXT;
       EXCEPTION WHEN duplicate_column THEN NULL; END $$""",
    # A database provisioned from a draft of this feature may carry row triggers that assume column layouts this store
    # does not use (and that recurse: the watchlists trigger updates watchlists from its own UPDATE). Both are dropped;
    # the store bumps watchlists.updated_at itself in the same transaction as every change, which is precise and cannot
    # loop. The shared function is left in place (no other trigger uses it).
    """DROP TRIGGER IF EXISTS trg_watchlist_items_touch ON watchlist_items""",
    """DROP TRIGGER IF EXISTS trg_watchlists_touch ON watchlists""",
    """DROP TRIGGER IF EXISTS trg_touch_watchlist ON watchlist_items""",
]

