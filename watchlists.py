class WatchlistError(Exception):
    """kind: unavailable | not_configured | not_found | duplicate | full | limit | invalid."""

    def __init__(self, kind, message):
        super().__init__(message)
        self.kind = kind


def seed_entries():
    """The one-time import as list entries (see `to_entry` for the pipeline shape)."""
    out = []
    for bucket, rows in UNIVERSE_SEED:
        for symbol, name, sector, news_query in rows:
            out.append({"symbol": symbol, "name": name, "sector": sector, "cap_segment": bucket,
                        "provider_symbol": f"NSE:{symbol}-EQ", "news_query": news_query})
    return out


def _now():
    return datetime.now(timezone.utc)


def _open_connection(url, timeout):
    """Only place psycopg is imported, so the dependency and tests can be swapped in one spot."""
    try:
        import psycopg
    except ImportError as e:  # pragma: no cover - dependency is in requirements.txt
        raise WatchlistError("not_configured", f"The PostgreSQL driver is missing ({e}). Install requirements.txt.")
    return psycopg.connect(url_for_libpq(url), connect_timeout=timeout)


def url_for_libpq(url):
    """A password pasted into a URL is usually NOT percent-encoded, and `?`, `#`, `/`, `:` or `@` inside it make the
    URL parse wrongly (`?` even starts a query string, so a password like `rX?$Bv` silently truncates the userinfo).
    When the password contains such a character, rebuild the URL with it escaped. Nothing else is touched."""
    url = str(url or "").strip()
    if "://" not in url or not url.lower().startswith(("postgres://", "postgresql://")):
        return url
    scheme, rest = url.split("://", 1)
    at = rest.rfind("@")
    if at < 0:
        return url
    userinfo, hostpart = rest[:at], rest[at + 1:]
    if ":" not in userinfo:
        return url
    user, password = userinfo.split(":", 1)
    if password == _quote(password, safe=""):  # already escaped (or nothing to escape)
        return url
    return f"{scheme}://{_quote(user, safe='')}:{_quote(password, safe='')}@{hostpart}"


def _iso(v):
    return v.isoformat() if hasattr(v, "isoformat") else v


class WatchlistStore:
    """Thread-safe PostgreSQL store for watchlists and their items (one shared, operator-owned dataset)."""

    def __init__(self, database_url, max_items=100, connect_timeout=10):
        self.url, self.max_items, self.connect_timeout = database_url, max_items, connect_timeout
        self._lock = threading.Lock()
        self._ready = False

    # ---------- plumbing ----------
    def configured(self):
        """A real libpq URL. A bare Supabase project URL (https://…) is a misconfiguration, reported by `status()`."""
        return bool(self.url) and self.url.startswith(("postgres://", "postgresql://"))

    def status(self):
        if not self.url:
            return {"ready": False, "error": "not_configured", "instruments": 0}
        if not self.configured():
            return {"ready": False, "error": "invalid_url", "instruments": 0}
        return {"ready": self._ready, "error": None, "instruments": None}

    def _connect(self):
        """One short-lived connection per operation (`connect_timeout` is passed to libpq)."""
        return _open_connection(self.url, self.connect_timeout)

    @contextmanager
    def _db(self):
        if not self.configured():
            raise WatchlistError("not_configured",
                                 "Watchlist storage is not configured: set SUPABASE_DATABASE_URL to the PostgreSQL "
                                 "connection string (postgresql://user:password@host:5432/postgres), not the project URL.")
        with self._lock:
            conn = self._connect()
            try:
                self._migrate(conn)
                yield conn
            finally:
                try:
                    conn.close()
                except Exception:
                    pass

    @staticmethod
    def _migrate(conn):
        with conn.cursor() as cur:
            for sql in MIGRATIONS:
                cur.execute(sql)
        conn.commit()

    @staticmethod
    def _row_to_item(r):
        return {"provider_symbol": r[0], "symbol": r[1], "name": r[2], "sector": r[3],
                "cap_segment": r[4], "position": r[5]}

    # ---------- seed (runs once, idempotent) ----------
    def ensure_seeded(self, entries=None, name=UNIVERSE_SEED_NAME):
        """Import the old universe.json once. Returns the number of rows inserted (0 when already done).

        Order matters: the advisory lock serialises concurrent workers, the migration marker makes the operation
        idempotent, and a pre-existing (non-empty) watchlist table also stops the import so a database that was already
        used for lists is never given a duplicate "Watchlist 1"."""
        entries = seed_entries() if entries is None else entries
        with self._db() as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT pg_try_advisory_xact_lock(%s)", (_SEED_LOCK,))
                if not cur.fetchone()[0]:
                    conn.rollback()
                    return 0
                cur.execute("SELECT 1 FROM watchlist_migrations WHERE key=%s", (_SEED_KEY,))
                if cur.fetchone():
                    conn.rollback()
                    return 0
                cur.execute("SELECT COUNT(*) FROM watchlists")
                if cur.fetchone()[0]:
                    # A previous version of the app already created lists: do not duplicate, just mark the import.
                    cur.execute("INSERT INTO watchlist_migrations(key) VALUES(%s) ON CONFLICT DO NOTHING", (_SEED_KEY,))
                    conn.commit()
                    return 0
                uid = self._insert_list(cur, name)
                for pos, e in enumerate(entries):
                    cur.execute("INSERT INTO watchlist_items(id,watchlist_id,provider_symbol,symbol,name,sector,cap_segment,"
                                " position) VALUES(%s,%s,%s,%s,%s,%s,%s,%s)",
                                (str(uuid.uuid4()), uid, e["provider_symbol"], e["symbol"], e["name"],
                                 e.get("sector"), e.get("cap_segment"), pos))
                cur.execute("INSERT INTO watchlist_migrations(key) VALUES(%s) ON CONFLICT DO NOTHING", (_SEED_KEY,))
            conn.commit()
            self._ready = True
            log.info("watchlists: imported the old universe.json as %r (%d stocks)", name, len(entries))
            return len(entries)

    @staticmethod
    def _insert_list(cur, name):
        for _ in range(5):  # the id is generated here; retry the astronomically unlikely collision
            uid = str(uuid.uuid4())
            try:
                cur.execute("INSERT INTO watchlists(id,name) VALUES(%s,%s)", (uid, name))
            except Exception as e:
                if "unique" in str(e).lower() or "duplicate" in str(e).lower():
                    continue
                raise
            return uid
        raise WatchlistError("invalid", "Could not allocate a watchlist id.")

    # ---------- reads ----------
    def lists(self):
        """[{id, name, count, updated_at}] in display order."""
        try:
            with self._db() as conn:
                with conn.cursor() as cur:
                    cur.execute("SELECT w.id, w.name, COUNT(i.id), w.updated_at FROM watchlists w "
                                "LEFT JOIN watchlist_items i ON i.watchlist_id=w.id "
                                "GROUP BY w.id, w.name, w.updated_at ORDER BY w.created_at, w.id")
                    out = [{"id": str(r[0]), "name": r[1], "count": int(r[2]), "updated_at": _iso(r[3])}
                           for r in cur.fetchall()]
                conn.rollback()
        except WatchlistError as e:
            self._ready = False
            if e.kind == "not_configured":
                raise
            raise WatchlistError("unavailable", str(e)) from e
        self._ready = True
        return out

    def get(self, uid):
        """One watchlist with items; raises WatchlistError('not_found') for an unknown id."""
        try:
            key = str(uuid.UUID(str(uid)))
        except ValueError:
            raise WatchlistError("not_found", "That watchlist no longer exists.")
        with self._db() as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT id, name, created_at, updated_at FROM watchlists WHERE id=%s", (key,))
                row = cur.fetchone()
                if not row:
                    conn.rollback()
                    raise WatchlistError("not_found", "That watchlist no longer exists.")
                cur.execute("SELECT provider_symbol, symbol, name, sector, cap_segment, position FROM watchlist_items "
                            "WHERE watchlist_id=%s ORDER BY position, created_at", (row[0],))
                items = [self._row_to_item(r) for r in cur.fetchall()]
            conn.rollback()
        return {"id": str(row[0]), "name": row[1], "items": items,
                "created_at": _iso(row[2]), "updated_at": _iso(row[3])}

    def first_id(self):
        with self._db() as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT id FROM watchlists ORDER BY created_at, id LIMIT 1")
                row = cur.fetchone()
            conn.rollback()
        return str(row[0]) if row else None

    # ---------- writes ----------
    def create(self, name):
        name = validate_name(name)
        with self._db() as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT COUNT(*) FROM watchlists")
                n = int(cur.fetchone()[0])
                if n >= MAX_LISTED:
                    conn.rollback()
                    raise WatchlistError("limit", f"At most {MAX_LISTED} watchlists are supported.")
                uid = self._insert_list(cur, name)
            conn.commit()
        return self.get(uid)

    def rename(self, uid, name):
        name = validate_name(name)
        with self._db() as conn:
            with conn.cursor() as cur:
                cur.execute("UPDATE watchlists SET name=%s, updated_at=now() WHERE id=%s", (name, _key(uid)))
                if cur.rowcount == 0:
                    conn.rollback()
                    raise WatchlistError("not_found", "That watchlist no longer exists.")
            conn.commit()
        return self.get(uid)

    def delete(self, uid):
        """Deletes a list; the last remaining list cannot be deleted (the dashboard always needs one)."""
        key = _key(uid)
        with self._db() as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT COUNT(*) FROM watchlists")
                if int(cur.fetchone()[0]) <= 1:
                    conn.rollback()
                    raise WatchlistError("limit", "Keep at least one watchlist.")
                cur.execute("DELETE FROM watchlists WHERE id=%s", (key,))
                if cur.rowcount == 0:
                    conn.rollback()
                    raise WatchlistError("not_found", "That watchlist no longer exists.")
            conn.commit()
        return True

    def add_item(self, uid, instrument, cap_segment=None):
        """Insert a catalogue-validated instrument. Duplicates are reported, never silently merged."""
        item = normalise_instrument(instrument, cap_segment)
        wid = _key(uid)
        with self._db() as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT id FROM watchlists WHERE id=%s", (wid,))
                if not cur.fetchone():
                    conn.rollback()
                    raise WatchlistError("not_found", "That watchlist no longer exists.")
                cur.execute("SELECT COUNT(*) FROM watchlist_items WHERE watchlist_id=%s", (wid,))
                n = int(cur.fetchone()[0])
                if n >= self.max_items:
                    conn.rollback()
                    raise WatchlistError("full", f"A watchlist holds at most {self.max_items} stocks.")
                try:
                    cur.execute("INSERT INTO watchlist_items(id,watchlist_id,provider_symbol,symbol,name,sector,"
                                "cap_segment,position) VALUES(%s,%s,%s,%s,%s,%s,%s,%s)",
                                (str(uuid.uuid4()), wid, item["provider_symbol"], item["symbol"], item["name"],
                                 item["sector"], item["cap_segment"], n))
                except Exception as e:
                    conn.rollback()
                    if "unique" in str(e).lower() or "duplicate" in str(e).lower():
                        raise WatchlistError("duplicate", f"{item['symbol']} is already in this watchlist.")
                    raise
                cur.execute("UPDATE watchlists SET updated_at=now() WHERE id=%s", (wid,))
            conn.commit()
        return self.get(uid)

    def remove_item(self, uid, provider_symbol):
        key = str(provider_symbol or "").strip().upper()
        wid = _key(uid)
        with self._db() as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT id FROM watchlists WHERE id=%s", (wid,))
                if not cur.fetchone():
                    conn.rollback()
                    raise WatchlistError("not_found", "That watchlist no longer exists.")
                cur.execute("DELETE FROM watchlist_items WHERE watchlist_id=%s AND provider_symbol=%s", (wid, key))
                if cur.rowcount == 0:
                    conn.rollback()
                    raise WatchlistError("not_found", "That stock is not in this watchlist.")
                cur.execute("UPDATE watchlists SET updated_at=now() WHERE id=%s", (wid,))
            conn.commit()
        return self.get(uid)


def _key(uid):
    """Watchlist ids are uuids; anything else cannot exist, so it is a not-found rather than a SQL error."""
    try:
        return str(uuid.UUID(str(uid)))
    except (ValueError, TypeError, AttributeError):
        raise WatchlistError("not_found", "That watchlist no longer exists.")


def validate_name(name):
    if not isinstance(name, str) or not name.strip():
        raise WatchlistError("invalid", "Give the watchlist a name.")
    name = " ".join(name.split())
    if len(name) > MAX_NAME:
        raise WatchlistError("invalid", f"Keep the name under {MAX_NAME} characters.")
    return name


def normalise_instrument(instrument, cap_segment=None):
    """Everything shown for a list item is re-read from the catalogue record the server resolved; the browser only
    ever supplies a provider symbol. The cap bucket is kept only when it is one Scout knows."""
    if not isinstance(instrument, dict) or not instrument.get("provider_symbol") \
            or not instrument.get("symbol") or not instrument.get("name"):
        raise WatchlistError("invalid", "That instrument cannot be added to a watchlist.")
    cap = cap_segment if cap_segment in CAP_BUCKETS else None
    return {"provider_symbol": str(instrument["provider_symbol"]).strip().upper(),
            "symbol": str(instrument["symbol"]).strip(), "name": str(instrument["name"]).strip(),
            "sector": (str(instrument["sector"]).strip() if instrument.get("sector") else None),
            "cap_segment": cap}


def to_entry(item):
    """List item -> the entry shape the pipeline has always used for Scout/Technician/Fundamentalist/Newsdesk.

    `fyers` is the provider id (the single place provider-specific ids are formed), `yf` the verified yfinance ticker
    (None when the series is not a plain equity, so analyst data is reported as a gap and never guessed)."""
    from data_sources import yf_symbol_for
    fyers = str(item.get("provider_symbol") or "").strip().upper()
    return {"symbol": item["symbol"], "name": item.get("name") or item["symbol"], "sector": item.get("sector"),
            "cap_segment": item.get("cap_segment"), "news_query": item.get("news_query") or None,
            "fyers": fyers, "yf": yf_symbol_for(fyers)}


def store_from_settings(settings):
    return WatchlistStore(settings.database_url, settings.watchlist_max_items)
